public sealed record CommitteeCase(
    int Id,
    int MeetingId,
    string CaseNo,
    string OriginalComplaintNo,
    string Accused,
    string AccusedAgency,
    string Investigator,
    string Division,
    string MeetingStatus,   // pending, reviewing, resolved
    string ResolutionType,  // none, reinvestigate, guilty_criminal, guilty_discipline, dismissed
    string ResolutionDetails,
    bool AlertSent
);

public sealed record CommitteeAudit(
    string Timestamp,
    string User,
    string Action,
    string Detail
);

