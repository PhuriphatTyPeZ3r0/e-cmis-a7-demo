    /// <summary>
    /// Returns CSS class for a given Rating string.
    /// ดีเด่น → "active" | ดี → "closed" | พอใช้ → "review" | ต้องปรับปรุง → "danger"
    /// </summary>
    public static string RatingClass(string r) => r switch
    {
        "ดีเด่น"       => "active",
        "ดี"            => "closed",
        "พอใช้"        => "review",
        "ต้องปรับปรุง" => "danger",
        _               => "closed"
    };

    /// <summary>
    /// Returns the average score for all records belonging to a department.
    /// Returns 0 when no records match.
    /// </summary>
    public static double DeptAvgScore(IEnumerable<PerformanceRecord> records, string dept)
    {
        var deptRecords = records.Where(r => r.Department == dept).ToList();
        return deptRecords.Count == 0 ? 0 : deptRecords.Average(r => r.Score);
    }

    /// <summary>
    /// Returns counts for each rating category across the supplied record set.
    /// </summary>
    public static (int Excellent, int Good, int Fair, int NeedsImprovement) RatingCounts(
        IEnumerable<PerformanceRecord> records)
    {
        int excellent = 0, good = 0, fair = 0, needs = 0;
        foreach (var r in records)
        {
            switch (r.Rating)
            {
                case "ดีเด่น":       excellent++; break;
                case "ดี":           good++;      break;
                case "พอใช้":       fair++;      break;
                case "ต้องปรับปรุง": needs++;    break;
            }
        }
        return (excellent, good, fair, needs);
    }
