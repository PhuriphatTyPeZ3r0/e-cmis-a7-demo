    public static IReadOnlyList<WitnessCase> Cases => cases;
    public static WitnessCase? GetById(int id) => cases.FirstOrDefault(c => c.Id == id);

    // ── SLA helpers ──────────────────────────────────────────────────────────
    public static int RoundDaysRemaining(WitnessCase c) => c.MaxRoundDays - c.CurrentRoundDays;
    public static int TotalDaysRemaining(WitnessCase c) => c.MaxTotalDays - c.ProtectionDays;

    public static string SlaRoundClass(WitnessCase c)
    {
        var rem = RoundDaysRemaining(c);
        if (rem <= 0)  return "sla-expired";
        if (rem <= 15) return "sla-warning";
        return "sla-safe";
    }

    public static double SlaRoundPercent(WitnessCase c) =>
        c.MaxRoundDays > 0 ? Math.Min(100, (double)c.CurrentRoundDays / c.MaxRoundDays * 100) : 0;

    public static double SlaTotalPercent(WitnessCase c) =>
        c.MaxTotalDays > 0 ? Math.Min(100, (double)c.ProtectionDays / c.MaxTotalDays * 100) : 0;

