    public static string RiskLevelFromScore(int score) => score switch
    {
        >= 80 => "สูงมาก",
        >= 55 => "สูง",
        >= 35 => "ปานกลาง",
        _      => "ต่ำ"
    };

    public static string RiskLevelClass(string level) => level switch
    {
        "สูงมาก"  => "danger",
        "สูง"     => "urgent",
        "ปานกลาง" => "review",
        _          => "active"
    };

    public static double SystemAvgScore(IEnumerable<RiskAgencyRecord> records)
    {
        var list = records.ToList();
        return list.Count == 0 ? 0.0 : list.Average(r => r.TotalScore);
    }

