    public static int DaysUntilExpiry(string expiryDateStr)
    {
        if (DateTime.TryParse(expiryDateStr, out var expiryDate))
        {
            var diff = expiryDate.Date - DateTime.Today;
            return (int)diff.TotalDays;
        }
        return 0;
    }

