    // ── SLA helpers (FR-027/028) ────────────────────────────────────────────
    // SLA 30+30 = 60 วัน สำหรับเบื้องต้น, 30+30+30+30 = 120 วัน สำหรับชี้มูล

    public static int DaysRemaining(InvestigationCase c) => c.MaxDays - c.DaysUsed;

    // FR-028: เหลือ ≤45 → เหลือง, เหลือ ≤30 หรือเกิน → แดง
    public static string SlaClass(InvestigationCase c)
    {
        var remaining = DaysRemaining(c);
        if (remaining <= 0)  return "sla-expired";
        if (remaining <= 30) return "sla-danger";
        if (remaining <= 45) return "sla-warning";
        return "sla-safe";
    }

    public static string SlaChipLabel(InvestigationCase c) => SlaLabel(c);

    public static string SlaLabel(InvestigationCase c)
    {
        var remaining = DaysRemaining(c);
        if (remaining <= 0)  return "เกินกำหนด!";
        return $"เหลือ {remaining} วัน";
    }

    public static double SlaPercent(InvestigationCase c) =>
        Math.Min(100, (double)c.DaysUsed / c.MaxDays * 100);

